# 单独出现易歧义的城市名（如“朝阳”“白山”“吉林”），要求后面紧跟“市/州/盟/地区”才计数
_AMBIGUOUS = {"朝阳", "吉林", "白山", "海南州", "阿里", "海北", "黄南", "玉树", "山南", "三沙",
              "中卫", "金昌", "白银", "通化", "七台河", "抚州", "宜春", "海东", "果洛", "海西"}

_TERM2CITY = {k: k for k in CITY}
_TERM2CITY.update(_ALIAS)
# 长词优先，避免“大理古城”被“大理”截断等
_pattern_parts = []
for _t in sorted(_TERM2CITY, key=len, reverse=True):
    _e = re.escape(_t)
    _pattern_parts.append(_e + "(?=[市州盟地])" if _t in _AMBIGUOUS else _e)
_CITY_RE = re.compile("|".join(_pattern_parts))


def match_cities(text: str):
    """返回文本中出现的城市计数 dict。"""
    hits = {}
    if not text:
        return hits
    for m in _CITY_RE.finditer(text):
        city = _TERM2CITY[m.group(0)]
        hits[city] = hits.get(city, 0) + 1
    return hits


def haversine_km(lat1, lon1, lat2, lon2):
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))
